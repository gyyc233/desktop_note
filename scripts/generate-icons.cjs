const sharp = require('sharp')
const fs = require('node:fs')
async function generate() {
  const sizes = [16, 24, 32, 48, 64, 128, 256]
  const images = await Promise.all(sizes.map(size => sharp('resources/notebook-tea-green.png').resize(size, size, { kernel: 'lanczos3' }).png().toBuffer()))
  await sharp('resources/notebook-tea-green.png').resize(256, 256, { kernel: 'lanczos3' }).png().toFile('resources/icon.png')
  const tray = await sharp('resources/notebook-tea-green.png').resize(32, 32, { kernel: 'lanczos3' }).png().toBuffer()
  fs.writeFileSync('resources/tray.png', tray)
  const header = Buffer.alloc(6 + sizes.length * 16)
  header.writeUInt16LE(1, 2); header.writeUInt16LE(sizes.length, 4)
  let offset = header.length
  sizes.forEach((size, i) => {
    const entry = 6 + i * 16
    header[entry] = size === 256 ? 0 : size; header[entry + 1] = header[entry]
    header.writeUInt16LE(1, entry + 4); header.writeUInt16LE(32, entry + 6)
    header.writeUInt32LE(images[i].length, entry + 8); header.writeUInt32LE(offset, entry + 12)
    offset += images[i].length
  })
  fs.writeFileSync('resources/icon.ico', Buffer.concat([header, ...images]))
  fs.writeFileSync('src/main/icons.ts', '// Generated by npm run icons. Do not edit manually.\n' +
    `export const appIconData = 'data:image/png;base64,${images.at(-1).toString('base64')}'\n` +
    `export const trayIconData = 'data:image/png;base64,${tray.toString('base64')}'\n`)
}
generate().catch(error => { console.error(error); process.exitCode = 1 })















