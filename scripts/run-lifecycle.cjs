const { spawnSync } = require('node:child_process')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const root = path.resolve(os.tmpdir())
const temporary = fs.mkdtempSync(path.join(root, 'desktop-note-lifecycle-'))
const result = spawnSync(require('electron'), [process.argv[2] === 'tasks' ? 'scripts/tasks-ui.cjs' : 'scripts/lifecycle.cjs'], { stdio: 'inherit', timeout: 30000, env: { ...process.env, NOTE_TEST_USER_DATA: temporary } })
if (path.dirname(path.resolve(temporary)) !== root || !path.basename(temporary).startsWith('desktop-note-lifecycle-')) throw new Error('Unexpected test directory')
fs.rmSync(temporary, { recursive: true, force: true, maxRetries: 3, retryDelay: 200 })
if (result.error) console.error(result.error)
process.exit(result.status ?? 1)
