const {app,BrowserWindow,dialog,screen,Menu} = require('electron')
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict')
const {collectBackup,encodeBackup,decodeBackup,restoreTasks,rollbackTasks,writeBackup}=require('../src/main/backup.ts')
const {openStore}=require('../src/main/store.ts')
const temp=process.env.NOTE_TEST_USER_DATA
if(!temp) throw Error('Use run-backup-tests.cjs')
app.setPath('userData',temp)
app.getAppPath=()=>temp
const password='backup-test-password'
const file=path.join(temp,'export.dnbak')
dialog.showSaveDialog=async()=>({canceled:false,filePath:file})
dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]})
dialog.showMessageBox=async()=>({response:1})
require('../out/main/index.js')
const delay=ms=>new Promise(r=>setTimeout(r,ms))
async function wait(window,expression){for(let i=0;i<150;i++){if(await window.webContents.executeJavaScript(expression))return;await delay(100)}throw Error('Timed out: '+expression)}
app.whenReady().then(async()=>{try{
 const window=BrowserWindow.getAllWindows()[0]
 const secondary=screen.getAllDisplays().find(d=>d.id!==screen.getPrimaryDisplay().id)
 if(secondary)window.setBounds({x:secondary.workArea.x+50,y:secondary.workArea.y+50,width:1100,height:760});else window.hide()
 await wait(window,`!document.querySelector('.today').disabled`)
 const tasks=path.join(temp,'tasks'), task=path.join(tasks,'中文任务')
 fs.mkdirSync(path.join(task,'img'),{recursive:true});fs.mkdirSync(path.join(task,'docs'))
 fs.writeFileSync(path.join(task,'task.md'),'# 图片\n![附件](img/test.png)')
 fs.writeFileSync(path.join(task,'img','test.png'),Buffer.from([0,1,255,4]))
 fs.writeFileSync(path.join(task,'docs','资料.txt'),'中文附件')
 const external=path.join(temp,'outside-task');fs.mkdirSync(external);fs.writeFileSync(path.join(external,'private.txt'),'must not include')
 const note={date:'2026-10-21',body:'# 原始笔记',category:'学习',bookmarked:true,updatedAt:'2026-10-21T01:00:00.000Z'}
 const source=openStore(path.join(temp,'source.db'),'a'.repeat(64));source.importNotes([note],true)
 const files=collectBackup(source.list(),tasks)
 assert.ok(!Object.keys(files).some(name=>name.includes('outside')))
 const encoded=await encodeBackup(files,password)
 assert.ok(!encoded.includes(Buffer.from('原始笔记')))
 await assert.rejects(decodeBackup(encoded,'wrong-password'),/密码错误/)
 const tampered=Buffer.from(encoded);tampered[tampered.length-1]^=1
 await assert.rejects(decodeBackup(tampered,password),/损坏/)
 const decoded=await decodeBackup(encoded,password);assert.deepEqual(decoded.notes,[note])
 const target=openStore(path.join(temp,'target.db'),'b'.repeat(64));target.save(note.date,'本地内容',false,'生活')
 assert.deepEqual(target.importNotes(decoded.notes,false),{imported:0,skipped:1});assert.equal(target.list()[0].body,'本地内容')
 assert.deepEqual(target.importNotes(decoded.notes,true),{imported:1,skipped:0});assert.deepEqual(target.list()[0],note)
 assert.throws(()=>target.importNotes([note,{...note,date:'2026-02-30'}],true));assert.deepEqual(target.list(),[note])
 const restored=restoreTasks(decoded.files,tasks);assert.equal(restored.length,1);assert.notEqual(restored[0],task)
 assert.deepEqual(fs.readFileSync(path.join(restored[0],'img','test.png')),Buffer.from([0,1,255,4]))
 assert.equal(fs.readFileSync(path.join(restored[0],'docs','资料.txt'),'utf8'),'中文附件')
 rollbackTasks(restored,tasks);assert.ok(!fs.existsSync(restored[0]));assert.ok(fs.existsSync(task))
 await assert.rejects(decodeBackup(await encodeBackup({...files,'tasks/../escape.txt':Buffer.from('evil')},password),password),/不安全路径/)
 source.close();target.close()
 console.log('PASS: encrypted ZIP round trip across database keys, wrong passwords, tampering, path traversal, conflict handling, task attachments and rollback')
 // Dirty edits must be flushed by the real backup panel before export.
 await window.webContents.executeJavaScript(`document.querySelector('.cm-content').focus()`)
 await window.webContents.insertText('未保存的备份测试')
 Menu.getApplicationMenu().items.find(item=>item.label==='文件').submenu.items.find(item=>item.label==='备份与恢复…').click()
 await wait(window,`!!document.querySelector('.backup-panel')`)
 const fill=(label,value)=>window.webContents.executeJavaScript(`(()=>{const input=document.querySelector('input[aria-label='+${JSON.stringify(JSON.stringify(label))}+']');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,${JSON.stringify(value)});input.dispatchEvent(new Event('input',{bubbles:true}))})()`)
 await fill('备份密码',password);await fill('确认备份密码',password)
 await window.webContents.executeJavaScript(`document.querySelector('.backup-actions button:last-child').click()`)
 await wait(window,`!!document.querySelector('.backup-panel [role=status]')`)
 const exported=await decodeBackup(fs.readFileSync(file),password)
 assert.ok(exported.notes.some(n=>n.body==='未保存的备份测试'))
 assert.ok(exported.files['tasks/中文任务/docs/资料.txt'])
 const importedNote={...note,date:'2026-10-22'}
 writeBackup(file,await encodeBackup(collectBackup([importedNote],tasks),password))
 await window.webContents.executeJavaScript(`document.querySelectorAll('.backup-tabs button')[1].click()`)
 await fill('备份密码',password)
 await window.webContents.executeJavaScript(`document.querySelector('.backup-actions button:last-child').click()`)
 await wait(window,`!!document.querySelector('.backup-panel [role=status]')`)
 assert.ok(await window.webContents.executeJavaScript(`window.notes.list().then(notes=>notes.some(n=>n.date==='2026-10-22'))`))
 const safety=fs.readdirSync(path.join(temp,'backups')).find(n=>n.endsWith('.dnbak'))
 const before=await decodeBackup(fs.readFileSync(path.join(temp,'backups',safety)),password)
 assert.ok(before.notes.some(n=>n.body==='未保存的备份测试'))
 await window.webContents.executeJavaScript(`document.querySelector('.backup-actions button').click()`)
 assert.ok(await window.webContents.executeJavaScript(`Array.from(document.querySelectorAll('.day')).some(day=>day.textContent.includes('10 月 22'))`))
 console.log('PASS: real export/import panel, dirty-note flush, task inclusion, automatic encrypted safety backup and refreshed archive')
 app.quit()
}catch(error){console.error(error);app.exit(1)}})
